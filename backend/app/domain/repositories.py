"""Interfaces (Protocol) de repositorios y Unit of Work."""
from __future__ import annotations

from datetime import date, datetime
from decimal import Decimal
from typing import Protocol
from uuid import UUID

from app.domain.entities import (
    Account,
    Budget,
    Category,
    CategoryTotal,
    Contribution,
    ContributionTotals,
    DailyTotal,
    ExportRow,
    Goal,
    MonthlyTotal,
    Notification,
    PushSubscription,
    RecurringRule,
    RefreshToken,
    Transaction,
    TopExpense,
    TransactionFilters,
    User,
)
from app.domain.enums import CategoryKind, TransactionType


class UserRepository(Protocol):
    async def get(self, id: UUID) -> User | None: ...
    async def get_by_email(self, email: str) -> User | None: ...
    async def add(self, user: User) -> User: ...
    async def update(self, user: User) -> User: ...
    async def count(self) -> int: ...
    async def list_all(self) -> list[User]: ...


class RefreshTokenRepository(Protocol):
    async def add(self, token: RefreshToken) -> RefreshToken: ...
    async def get_by_hash(self, token_hash: str) -> RefreshToken | None: ...
    async def revoke(self, id: UUID) -> None: ...
    async def revoke_all_for_user(self, user_id: UUID) -> None: ...
    async def delete_expired(self, now: datetime) -> None: ...


class AccountRepository(Protocol):
    async def list(self, user_id: UUID, include_archived: bool) -> list[Account]: ...
    async def get(self, user_id: UUID, id: UUID) -> Account | None: ...
    async def add(self, account: Account) -> Account: ...
    async def update(self, account: Account) -> Account: ...
    async def delete(self, user_id: UUID, id: UUID) -> None: ...
    async def has_dependencies(self, user_id: UUID, id: UUID) -> bool: ...


class CategoryRepository(Protocol):
    async def list(self, user_id: UUID, kind: CategoryKind | None) -> list[Category]: ...
    async def get(self, user_id: UUID, id: UUID) -> Category | None: ...
    async def add(self, category: Category) -> Category: ...
    async def add_many(self, categories: list[Category]) -> None: ...
    async def update(self, category: Category) -> Category: ...
    async def delete(self, user_id: UUID, id: UUID) -> None: ...
    async def name_exists(
        self, user_id: UUID, kind: CategoryKind, name: str, exclude_id: UUID | None = None
    ) -> bool: ...
    async def in_use(self, user_id: UUID, id: UUID) -> bool: ...


class TransactionRepository(Protocol):
    async def list(
        self, user_id: UUID, filters: TransactionFilters, page: int, page_size: int
    ) -> tuple[list[Transaction], int]: ...
    async def get(self, user_id: UUID, id: UUID) -> Transaction | None: ...
    async def add(self, tx: Transaction) -> Transaction: ...
    async def update(self, tx: Transaction) -> Transaction: ...
    async def delete(self, user_id: UUID, id: UUID) -> None: ...
    async def totals(self, user_id: UUID, start: date, end: date) -> tuple[Decimal, Decimal]: ...
    async def salary_total(self, user_id: UUID, start: date, end: date) -> Decimal:
        """Ingresos de sueldo del rango: generados por una regla `is_paycheck` o registrados a mano
        en la categoría de una regla de sueldo activa."""
        ...
    async def salary_dates(self, user_id: UUID, until: date) -> list[date]:
        """Fechas distintas (<= `until`) con ingresos de sueldo, ascendentes."""
        ...
    async def category_totals(
        self, user_id: UUID, start: date, end: date, type: TransactionType
    ) -> list[CategoryTotal]: ...
    async def spent_by_category(
        self, user_id: UUID, start: date, end: date
    ) -> dict[UUID, Decimal]: ...
    async def monthly_totals(self, user_id: UUID, start: date, end: date) -> list[MonthlyTotal]: ...
    async def recent(self, user_id: UUID, limit: int) -> list[Transaction]: ...
    async def export_rows(self, user_id: UUID, start: date, end: date) -> list[ExportRow]: ...
    async def daily_totals(self, user_id: UUID, start: date, end: date) -> list[DailyTotal]:
        """Un elemento por día con movimiento (sin transferencias), con el ingreso de sueldo aparte."""
        ...
    async def top_expenses(
        self, user_id: UUID, start: date, end: date, limit: int
    ) -> list[TopExpense]: ...


class BudgetRepository(Protocol):
    async def list_for_month(self, user_id: UUID, month: date) -> list[Budget]: ...
    async def get(self, user_id: UUID, id: UUID) -> Budget | None: ...
    async def find(self, user_id: UUID, category_id: UUID, month: date) -> Budget | None: ...
    async def add(self, budget: Budget) -> Budget: ...
    async def update(self, budget: Budget) -> Budget: ...
    async def delete(self, user_id: UUID, id: UUID) -> None: ...


class RecurringRepository(Protocol):
    async def list(self, user_id: UUID) -> list[RecurringRule]: ...
    async def get(self, user_id: UUID, id: UUID) -> RecurringRule | None: ...
    async def add(self, rule: RecurringRule) -> RecurringRule: ...
    async def update(self, rule: RecurringRule) -> RecurringRule: ...
    async def delete(self, user_id: UUID, id: UUID) -> None: ...
    async def lock_due(self, user_id: UUID, today: date) -> list[RecurringRule]:
        """Reglas activas con next_run_date <= today, bloqueadas (SELECT ... FOR UPDATE)."""
        ...


class GoalRepository(Protocol):
    async def list(self, user_id: UUID) -> list[Goal]: ...
    async def get(self, user_id: UUID, id: UUID) -> Goal | None: ...
    async def add(self, goal: Goal) -> Goal: ...
    async def update(self, goal: Goal) -> Goal: ...
    async def delete(self, user_id: UUID, id: UUID) -> None: ...
    async def list_contributions(self, user_id: UUID, goal_id: UUID) -> list[Contribution]: ...
    async def get_contribution(
        self, user_id: UUID, goal_id: UUID, id: UUID
    ) -> Contribution | None: ...
    async def add_contribution(self, c: Contribution) -> Contribution: ...
    async def delete_contribution(self, user_id: UUID, id: UUID) -> None: ...
    async def contribution_totals(
        self, user_id: UUID, start: date, end: date
    ) -> dict[UUID, ContributionTotals]: ...


class NotificationRepository(Protocol):
    async def try_add(self, n: Notification) -> bool:
        """Inserta; False si ya existe (user_id, dedupe_key)."""
        ...
    async def get(self, user_id: UUID, id: UUID) -> Notification | None: ...
    async def list(
        self, user_id: UUID, unread_only: bool, page: int, page_size: int
    ) -> tuple[list[Notification], int]: ...
    async def unread_count(self, user_id: UUID) -> int: ...
    async def mark_read(self, user_id: UUID, id: UUID) -> None: ...
    async def mark_all_read(self, user_id: UUID) -> None: ...


class PushSubscriptionRepository(Protocol):
    async def upsert(self, sub: PushSubscription) -> PushSubscription:
        """Por endpoint (único global): si existe se actualiza y se reasigna al usuario."""
        ...
    async def list_for_user(self, user_id: UUID) -> list[PushSubscription]: ...
    async def delete_by_endpoint(self, user_id: UUID, endpoint: str) -> None: ...
    async def delete(self, id: UUID) -> None: ...


class UnitOfWork(Protocol):
    users: UserRepository
    tokens: RefreshTokenRepository
    accounts: AccountRepository
    categories: CategoryRepository
    transactions: TransactionRepository
    budgets: BudgetRepository
    recurring: RecurringRepository
    goals: GoalRepository
    notifications: NotificationRepository
    push_subscriptions: PushSubscriptionRepository

    async def commit(self) -> None: ...
    async def rollback(self) -> None: ...
    async def __aenter__(self) -> "UnitOfWork": ...
    async def __aexit__(self, *exc) -> None: ...
